#!/usr/bin/env node
/**
 * Exports the database *structure* (no data) to tests/db/schema.sql.
 * CI loads that file into an empty Postgres before running integration tests.
 *
 * Usage:  npm run db:dump-schema               (reads .env.production)
 *         npm run db:dump-schema -- .env.test  (any env file with DB_* vars)
 *
 * Safety: the session is forced read-only (default_transaction_read_only=on), so
 * the export cannot modify the source database. Requires pg_dump >= the server version.
 */
const { spawnSync } = require("child_process");
const fs = require("fs");
const path = require("path");
const dotenv = require("dotenv");

const envFile = process.argv[2] || ".env.production";
const root = path.resolve(__dirname, "..");
const outFile = path.join(root, "tests", "db", "schema.sql");

const parsed = dotenv.config({ path: path.join(root, envFile), quiet: true }).parsed;
if (!parsed) {
  console.error(`Could not read ${envFile}`);
  process.exit(1);
}
const { DB_HOST, DB_PORT, DB_USERNAME, DB_PASSWORD, DB_NAME } = parsed;

const result = spawnSync(
  "pg_dump",
  ["--schema-only", "--schema=public", "--no-owner", "--no-privileges", "--no-comments"],
  {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
    env: {
      ...process.env,
      PGHOST: DB_HOST,
      PGPORT: DB_PORT,
      PGUSER: DB_USERNAME,
      PGPASSWORD: DB_PASSWORD,
      PGDATABASE: DB_NAME,
      PGSSLMODE: process.env.PGSSLMODE || "prefer",
      PGOPTIONS: "-c default_transaction_read_only=on",
    },
  },
);

if (result.error || result.status !== 0) {
  console.error(result.error?.message || result.stderr);
  process.exit(result.status || 1);
}

const sql = result.stdout
  .split(/\r?\n/)
  // PG 18 adds `\restrict <random key>` / `\unrestrict` guards with a new key on every run,
  // which would make each re-export a noisy diff. They only matter for untrusted dumps.
  .filter((line) => !/^\\(un)?restrict\b/.test(line))
  // Server/client version banners change with patch releases; keep the diff about structure.
  .filter((line) => !/^-- Dumped (from database|by pg_dump) version/.test(line))
  // A fresh database already has `public`; a plain CREATE SCHEMA would abort the load.
  .map((line) => (line === "CREATE SCHEMA public;" ? "CREATE SCHEMA IF NOT EXISTS public;" : line))
  .join("\n");

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(
  outFile,
  `-- Generated by scripts/dump-schema.cjs from ${envFile}. Structure only, no data.\n` +
    `-- Regenerate with: npm run db:dump-schema\n` +
    sql.replace(/\n{3,}/g, "\n\n"),
);
console.log(`Wrote ${path.relative(root, outFile)} (${sql.length} bytes)`);
